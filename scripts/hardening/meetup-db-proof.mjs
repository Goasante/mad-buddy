/** Isolated, in-memory PostgreSQL proof. Never connects to a remote database. */
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const modulePath = process.env.MEETUP_PGLITE_MODULE;
if (!modulePath) throw new Error('Set MEETUP_PGLITE_MODULE to the isolated PGlite module.');
const { PGlite } = await import(modulePath);
const db = new PGlite();
const A='10000000-0000-4000-8000-000000000001', B='10000000-0000-4000-8000-000000000002';
const C='10000000-0000-4000-8000-000000000003', D='10000000-0000-4000-8000-000000000004';
await db.exec(`create schema auth; create table auth.users(id uuid primary key);
  create role anon; create role authenticated; create role service_role bypassrls;
  create table public.profiles(user_id uuid primary key,full_name text);
  create table public.friendships(user_one_id uuid,user_two_id uuid,ended_at timestamptz);
  create table public.blocked_users(blocker_id uuid,blocked_id uuid);
  insert into auth.users values ('${A}'),('${B}'),('${C}'),('${D}');
  insert into public.profiles values ('${A}','Ama'),('${B}','Kofi'),('${C}','Esi'),('${D}','Outsider');
  insert into public.friendships values ('${A}','${B}',null),('${A}','${C}',null);`);
await db.exec(readFileSync('supabase/migrations/20261006161651_meet_up_core.sql','utf8'));
let checks=0;
const command = async (actor, action, input) => {
  const r=await db.query('select public.meetup_command_server($1,$2,$3::jsonb) result',[actor,action,JSON.stringify(input)]);
  return r.rows[0].result;
};
const list=async actor=>(await db.query('select public.list_meetups_server($1) result',[actor])).rows[0].result;
let seq=0;
const key=()=>`20000000-0000-4000-8000-${String(++seq).padStart(12,'0')}`;
const future=new Date(Date.now()+60*60_000).toISOString();
const base={mode:'meet_somewhere',placeLabel:'Our usual cafe',when:'later',startsAt:future,timezone:'Africa/Accra',participantIds:[B,C],requestKey:key()};
const created=await command(A,'create',base);
assert.equal((await command(A,'create',base)).id,created.id); checks++;
assert.equal((await list(D)).length,0); checks++;
const bView=(await list(B))[0];
assert.equal(bView.members.find(m=>m.name==='Another Muddy').userId,null); checks++;
const mutate=(actor,action,input={})=>command(actor,action,{id:created.id,revision:1,requestKey:key(),...input});
await assert.rejects(mutate(D,'cancel'),/MEETUP_ACCESS/); checks++;
await assert.rejects(mutate(B,'arrival',{arrival:'here'}),/MEETUP_ACCEPT_FIRST/); checks++;
await mutate(B,'respond',{response:'accepted'});
await mutate(B,'proximity',{enabled:true});
assert.equal((await list(B))[0].members.find(m=>m.userId===B).proximityEnabled,true); checks++;
await mutate(B,'arrival',{arrival:'here'});
assert.equal((await list(A))[0].members.find(m=>m.userId===B).arrival,'here'); checks++;
await mutate(B,'met');
assert.equal((await list(A))[0].members.filter(m=>m.metAt).length,1); checks++;
await mutate(C,'suggest',{startsAt:new Date(Date.now()+2*60*60_000).toISOString()});
assert.equal(Date.parse((await list(A))[0].startsAt),Date.parse(future)); checks++;
const reschedule={id:created.id,revision:1,requestKey:key(),startsAt:new Date(Date.now()+3*60*60_000).toISOString()};
await command(A,'reschedule',reschedule);
assert.equal((await command(A,'reschedule',reschedule)).revision,2); checks++;
const after=(await list(B))[0];
assert.equal(after.members.find(m=>m.userId===B).response,'invited');
assert.equal(after.members.find(m=>m.userId===B).metAt,null); checks++;
assert.equal(after.members.find(m=>m.userId===B).proximityEnabled,false); checks++;
await assert.rejects(mutate(B,'respond',{response:'accepted'}),/MEETUP_CHANGED/); checks++;
await db.query('insert into public.blocked_users values($1,$2)',[A,B]);
assert.equal((await list(B)).length,0); checks++;
await db.exec('delete from public.blocked_users');
const visit=await command(A,'create',{...base,mode:'coming_to',participantIds:[B],requestKey:key()});
await command(B,'respond',{id:visit.id,revision:1,response:'declined',requestKey:key()});
assert.equal((await list(A)).find(m=>m.id===visit.id).status,'cancelled'); checks++;
await assert.rejects(command(A,'create',{...base,participantIds:[D],requestKey:key()}),/MEETUP_NOT_MUDDIES/); checks++;
const grants=await db.query(`select has_function_privilege('authenticated','public.meetup_command_server(uuid,text,jsonb)','EXECUTE') allowed,
  has_table_privilege('anon','public.meetups','SELECT') readable`);
assert.equal(grants.rows[0].allowed,false); assert.equal(grants.rows[0].readable,false); checks++;
const claims=(await db.query('select public.claim_meetup_notifications(100) result')).rows[0].result;
assert.ok(claims.length>0); checks++;
const row=claims[0];
assert.equal((await db.query('select public.meetup_notification_allowed($1,$2) result',[row.id,row.lease_id])).rows[0].result,true); checks++;
await db.query('insert into public.blocked_users values($1,$2)',[row.sender_id,row.recipient_id]);
assert.equal((await db.query('select public.meetup_notification_allowed($1,$2) result',[row.id,row.lease_id])).rows[0].result,false); checks++;
await db.exec('delete from public.blocked_users');
assert.equal((await db.query('select public.finish_meetup_notification($1,$2,true) result',[row.id,key()])).rows[0].result,false); checks++;
assert.equal((await db.query('select public.finish_meetup_notification($1,$2,true) result',[row.id,row.lease_id])).rows[0].result,true); checks++;
// Due reminders use the CURRENT revision, accepted host, and unique milestones.
const reminder=await command(A,'create',{...base,mode:'come_over',participantIds:[B],requestKey:key()});
await command(B,'respond',{id:reminder.id,revision:1,response:'accepted',requestKey:key()});
await db.query("update public.meetups set starts_at=now()+interval '20 minutes',arranged_at=now()-interval '1 hour' where id=$1",[reminder.id]);
await db.query('select public.claim_meetup_notifications(100)');
const reminderCount=async()=>Number((await db.query("select count(*) n from public.meetup_notification_outbox where meetup_id=$1 and event='reminder_30'",[reminder.id])).rows[0].n);
assert.equal(await reminderCount(),2); checks++;
await db.query('select public.claim_meetup_notifications(100)');
assert.equal(await reminderCount(),2); checks++;
const queuedReminder=(await db.query("select id,lease_id from public.meetup_notification_outbox where meetup_id=$1 and recipient_id=$2 and event='reminder_30'",[reminder.id,B])).rows[0];
const allowed=async row=>(await db.query('select public.meetup_notification_allowed($1,$2) result',[row.id,row.lease_id])).rows[0].result;
assert.equal(await allowed(queuedReminder),true); checks++;
await command(B,'arrival',{id:reminder.id,revision:1,requestKey:key(),arrival:'here'});
assert.equal(await allowed(queuedReminder),false); checks++;
await command(B,'arrival',{id:reminder.id,revision:1,requestKey:key(),arrival:'on_my_way'});
await db.query("update public.meetups set starts_at=now()+interval '4 minutes' where id=$1",[reminder.id]);
assert.equal(await allowed(queuedReminder),false); checks++;
await command(A,'reschedule',{id:reminder.id,revision:1,requestKey:key(),startsAt:new Date(Date.now()+60*60_000).toISOString()});
await db.query('select public.claim_meetup_notifications(100)');
assert.equal(Number((await db.query("select count(*) n from public.meetup_notification_outbox where meetup_id=$1 and event='reminder_30' and status<>'discarded'",[reminder.id])).rows[0].n),0); checks++;
const invite=await command(A,'create',{...base,participantIds:[B],requestKey:key()});
await db.query('select public.claim_meetup_notifications(100)');
const inviteRow=(await db.query("select id,lease_id from public.meetup_notification_outbox where meetup_id=$1 and event='invited'",[invite.id])).rows[0];
assert.equal(await allowed(inviteRow),true); checks++;
await command(B,'respond',{id:invite.id,revision:1,requestKey:key(),response:'accepted'});
assert.equal(await allowed(inviteRow),false); checks++;
await db.query('select public.claim_meetup_notifications(100)');
const acceptedRow=(await db.query("select id,lease_id from public.meetup_notification_outbox where meetup_id=$1 and event='accepted'",[invite.id])).rows[0];
assert.equal(await allowed(acceptedRow),true); checks++;
await command(B,'respond',{id:invite.id,revision:1,requestKey:key(),response:'declined'});
assert.equal(await allowed(acceptedRow),false); checks++;
// Execute the same RPC as the actual invoker role, not just the database owner.
await db.exec('grant select on public.profiles,public.friendships,public.blocked_users to service_role; set role service_role');
assert.ok((await list(A)).length>0); checks++;
await db.exec('reset role; set role authenticated');
await assert.rejects(db.query('select public.list_meetups_server($1)',[A]),/permission denied/); checks++;
await db.exec('reset role');
console.log(`Meet Up isolated database proof: ${checks} checks passed.`);
await db.close();
